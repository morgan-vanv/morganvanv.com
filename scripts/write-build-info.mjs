// Writes src/build-info.prod.ts from the current git commit, for the /now page's "Site" row.
// Runs automatically before `npm run build` (the `prebuild` npm hook). The production build swaps
// it in for the committed src/build-info.ts via `fileReplacements` in angular.json.
//
// GitHub merges arrive as "Merge pull request #80 from owner/branch" with the PR title as the
// body's first line, so for those the PR title is used instead (with its number).
import { execFileSync } from 'node:child_process';
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const out = fileURLToPath(new URL('../src/build-info.prod.ts', import.meta.url));

function git(...args) {
  // stderr ignored so a missing repo doesn't print git's own "fatal:" line; we warn below.
  return execFileSync('git', args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'] }).trim();
}

let info;
try {
  const [sha, date, subject, ...bodyLines] = git('log', '-1', '--format=%H%n%cI%n%s%n%b').split('\n');
  const merge = /^Merge pull request #(\d+)/.exec(subject);
  const prTitle = bodyLines.find(line => line.trim())?.trim();
  info = {
    sha,
    date,
    message: merge && prTitle ? `${prTitle} (#${merge[1]})` : subject,
  };
} catch (error) {
  // No git (e.g. a source tarball): build anyway, the row just shows nothing.
  console.warn(`write-build-info: git unavailable, writing an empty build info (${error.message})`);
  info = { sha: '', date: '', message: '' };
}

// Self-contained on purpose (no imports): this file is gitignored and outlives branch switches,
// so it must still compile on a branch that doesn't have build-info.model.ts.
writeFileSync(out, `// Generated by scripts/write-build-info.mjs — do not edit or commit.
export const BUILD_INFO: { sha: string; date: string; message: string } = ${JSON.stringify(info, null, 2)};
`);
console.log(`write-build-info: ${info.sha.slice(0, 7) || '(none)'} ${info.message}`);
